# Generates src/ws_version.h, which defines WS_BUILD: the semver build metadata
# appended to WS_VERSION (src/wippersnapper.h) so every artifact names the exact
# commit and CI run it was built from (adafruit/Adafruit_Wippersnapper_Arduino#1023).
#
#   CI build (non-tag)   WS_BUILD "+<sha>.<run-number>"
#   local build          WS_BUILD "+<sha>" or "+<sha>-dirty"
#   tagged clean build   WS_BUILD ""  (releases keep the plain version)
#
# The header is gitignored; the firmware falls back to WS_BUILD "" without it.
#
# CI:         python3 generate_ws_version.py [--sha <commit>]
#             (the run number is read from GITHUB_RUN_NUMBER)
# PlatformIO: extra_scripts = pre:generate_ws_version.py
import argparse
import os
import subprocess

HEADER = """// Generated by generate_ws_version.py - do not edit or commit.
#ifndef WS_VERSION_H
#define WS_VERSION_H
#define WS_BUILD "{build}" ///< semver build metadata appended to WS_VERSION
#endif // WS_VERSION_H
"""


def git(root, *args):
    """Runs git in root, returns stripped stdout or None on failure."""
    try:
        out = subprocess.run(
            ["git", *args],
            cwd=root,
            capture_output=True,
            text=True,
            check=True,
        )
    except (OSError, subprocess.CalledProcessError):
        return None
    return out.stdout.strip()


def build_metadata(root, sha=None):
    """Returns the WS_BUILD string, or None when git is unavailable."""
    head = git(root, "rev-parse", "HEAD")
    if head is None:
        return None
    # Only tracked changes count, matching `git describe --dirty`
    dirty = bool(git(root, "status", "--porcelain", "--untracked-files=no"))
    tagged = git(root, "describe", "--exact-match", "--tags", "HEAD") is not None
    if tagged and not dirty:
        return ""
    build = "+" + (sha or head)[:8]
    if dirty:
        build += "-dirty"
    run_number = os.environ.get("GITHUB_RUN_NUMBER")
    if run_number:
        build += "." + run_number
    return build


def write_header(root, sha=None):
    """Writes src/ws_version.h, leaving it untouched if nothing changed."""
    build = build_metadata(root, sha)
    if build is None:
        print("generate_ws_version.py: git unavailable, WS_BUILD not generated")
        return
    path = os.path.join(root, "src", "ws_version.h")
    content = HEADER.format(build=build)
    try:
        with open(path, encoding="utf-8") as f:
            if f.read() == content:
                return
    except OSError:
        pass
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(content)
    print("generate_ws_version.py: WS_BUILD=\"%s\"" % build)


try:
    Import("env")  # noqa: F821 - defined when run as a PlatformIO extra_script
except NameError:
    env = None

if env is not None:
    write_header(env.subst("$PROJECT_DIR"))
elif __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Generate src/ws_version.h")
    parser.add_argument(
        "--sha",
        help="commit to report instead of HEAD (e.g. a PR's head commit)",
    )
    args = parser.parse_args()
    write_header(os.path.dirname(os.path.abspath(__file__)), args.sha)
